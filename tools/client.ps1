[CmdletBinding()]
param(
    [ValidateSet('Prepare', 'Test', 'Run', 'Build')]
    [string] $Action = 'Run',
    [string] $ConfigPath = '',
    [string] $FlutterPath = 'flutter',
    [ValidateSet('Debug', 'Release')]
    [string] $Configuration = 'Release',
    [switch] $Dev
)

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
Push-Location -LiteralPath $projectRoot
try {
    $values = @{}
    if ($ConfigPath) {
        $document = Get-Content -LiteralPath (Resolve-Path -LiteralPath $ConfigPath).Path -Raw -Encoding UTF8 | ConvertFrom-Json
        if ($document -isnot [PSCustomObject]) { throw 'Client config must be a JSON object.' }
        foreach ($property in $document.PSObject.Properties) {
            $values[$property.Name] = $property.Value
        }
    } else {
        foreach ($key in @('METRON_BASE_URL', 'METRON_SUBSCRIPTION_BASE_URL', 'CRISP_WEBSITE_ID', 'APP_DISPLAY_NAME', 'APP_VERSION', 'APP_BUILD_NUMBER')) {
            $value = [Environment]::GetEnvironmentVariable($key)
            if ($null -ne $value) { $values[$key] = $value }
        }
    }
    $config = [PSCustomObject] $values
    if (!$values.ContainsKey('METRON_SUBSCRIPTION_BASE_URL')) {
        $values['METRON_SUBSCRIPTION_BASE_URL'] = ''
        $config = [PSCustomObject] $values
    }
    foreach ($key in @('METRON_BASE_URL', 'CRISP_WEBSITE_ID', 'APP_DISPLAY_NAME', 'APP_VERSION', 'APP_BUILD_NUMBER')) {
        if ($config.$key -isnot [string] -or [string]::IsNullOrWhiteSpace($config.$key)) {
            throw "Build parameter $key must be a non-empty string. Supply workflow inputs or environment variables."
        }
    }
    $panel = [Uri] $config.METRON_BASE_URL
    if (!$panel.IsAbsoluteUri -or $panel.Scheme -ne 'https' -or !$panel.Host -or $panel.UserInfo -or $panel.Query -or $panel.Fragment) {
        throw 'METRON_BASE_URL must be an HTTPS URL without credentials, query or fragment.'
    }
    if ($config.METRON_SUBSCRIPTION_BASE_URL -isnot [string]) {
        throw 'METRON_SUBSCRIPTION_BASE_URL must be a string.'
    }
    if ($config.METRON_SUBSCRIPTION_BASE_URL -ne '') {
        $subscription = [Uri] $config.METRON_SUBSCRIPTION_BASE_URL
        if (!$subscription.IsAbsoluteUri -or $subscription.Scheme -ne 'https' -or !$subscription.Host -or
            $subscription.UserInfo -or $subscription.Query -or $subscription.Fragment -or $subscription.AbsolutePath -ne '/') {
            throw 'METRON_SUBSCRIPTION_BASE_URL must be an HTTPS origin without a path, credentials, query or fragment.'
        }
    }
    if ($config.CRISP_WEBSITE_ID -notmatch '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$') {
        throw 'CRISP_WEBSITE_ID must be a UUID.'
    }
    if ($config.APP_DISPLAY_NAME.Length -gt 64 -or $config.APP_DISPLAY_NAME -match '[\x00-\x1f"<>:/\\|?*]' -or $config.APP_DISPLAY_NAME -match '[ .]$') {
        throw 'APP_DISPLAY_NAME must be a safe Windows display/folder name, at most 64 characters.'
    }
    if ($config.APP_VERSION -notmatch '^\d+\.\d+\.\d+$' -or $config.APP_BUILD_NUMBER -notmatch '^\d{1,10}$' -or
        [long] $config.APP_BUILD_NUMBER -gt [int]::MaxValue) {
        throw 'APP_VERSION must be x.y.z and APP_BUILD_NUMBER must be a non-negative 32-bit integer string.'
    }
    New-Item -ItemType Directory -Path '.dart_tool' -Force | Out-Null
    $configFile = Join-Path $projectRoot '.dart_tool/client-build-inputs.json'
    [IO.File]::WriteAllText($configFile, ($values | ConvertTo-Json), [Text.UTF8Encoding]::new($false))
    function Write-GeneratedFile([string] $Path, [string] $Content) {
        $absolute = Join-Path $projectRoot $Path
        $contentWithNewline = $Content.TrimEnd() + "`n"
        if (!(Test-Path -LiteralPath $absolute) -or [IO.File]::ReadAllText($absolute) -cne $contentWithNewline) {
            [IO.File]::WriteAllText($absolute, $contentWithNewline, [Text.UTF8Encoding]::new($false))
        }
    }
    # Keep generated literals valid even when branding contains quotes or $.
    function Dart-String([string] $Value) {
        $escaped = $Value.Replace('\', '\\').Replace("'", "\'").Replace('$', '\$').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
        return "'" + $escaped + "'"
    }
    $dartConfig = @"
// GENERATED by tools/client.ps1 from build inputs. Do not commit release values.
class ClientDefaults {
  static const panelUrl = $(Dart-String $config.METRON_BASE_URL);
  static const subscriptionBaseUrl = $(Dart-String $config.METRON_SUBSCRIPTION_BASE_URL);
  static const crispWebsiteId = $(Dart-String $config.CRISP_WEBSITE_ID);
  static const displayName = $(Dart-String $config.APP_DISPLAY_NAME);
  static const version = $(Dart-String $config.APP_VERSION);
  static const buildNumber = $(Dart-String $config.APP_BUILD_NUMBER);
}
"@
    Write-GeneratedFile 'lib/common/client_config.g.dart' $dartConfig
    $nativeName = $config.APP_DISPLAY_NAME + $(if ($Dev) { ' 测试版' } else { '' })
    $nativeHeader = @"
// GENERATED by tools/client.ps1 from build inputs. Do not commit release values.
#pragma once
#define CLIENT_DISPLAY_NAME_UTF8 "$nativeName"
#define CLIENT_DISPLAY_NAME_WIDE L"$nativeName"
"@
    Write-GeneratedFile 'windows/runner/client_branding.h' $nativeHeader
    $pubspecPath = Join-Path $projectRoot 'pubspec.yaml'
    $pubspec = [IO.File]::ReadAllText($pubspecPath)
    if ([regex]::Matches($pubspec, '(?m)^version:[^\r\n]*').Count -ne 1) {
        throw 'Expected exactly one version entry in pubspec.yaml.'
    }
    $updated = [regex]::Replace($pubspec, '(?m)^version:[^\r\n]*', "version: $($config.APP_VERSION)+$($config.APP_BUILD_NUMBER)")
    if ($updated -cne $pubspec) {
        [IO.File]::WriteAllText($pubspecPath, $updated, [Text.UTF8Encoding]::new($false))
    }
    Write-Host 'Client build parameters validated.'
    if ($Action -eq 'Prepare') { return }

    $defines = @("--dart-define-from-file=$configFile")
    if ($Dev) { $defines += '--dart-define=APP_DEV=true' }
    if ($Action -eq 'Test') {
        $defines += "--dart-define=CLIENT_CONFIG_FILE=$configFile"
        $testFiles = @('test/common/client_config_test.dart', 'test/common/metron_session_test.dart',
            'test/common/crisp_support_test.dart', 'test/common/metron_account_test.dart',
            'test/common/metron_profile_transaction_test.dart', 'test/pages/metron_login_test.dart',
            'test/providers/metron_navigation_test.dart', 'test/providers/metron_features_test.dart')
        & $FlutterPath test --no-pub @defines @testFiles
        if ($LASTEXITCODE -ne 0) { throw "Flutter tests failed ($LASTEXITCODE)." }
        & node (Join-Path $PSScriptRoot 'test_crisp_identity.js')
        if ($LASTEXITCODE -ne 0) { throw 'Crisp identity JavaScript regression failed.' }
        return
    }
    $coreName = if ($Dev) { 'BettboxDevCore.exe' } else { 'BettboxCore.exe' }
    $coreFile = Join-Path $projectRoot "libclash/windows/$coreName"
    if (!(Test-Path -LiteralPath $coreFile)) {
        throw "Missing $coreName. Build the matching core with setup.dart first; existing local dev cores require -Dev."
    }
    $coreHash = (Get-FileHash -LiteralPath $coreFile -Algorithm SHA256).Hash.ToLowerInvariant()
    $defines += "--dart-define=CORE_SHA256=$coreHash"
    $defines += '--dart-define=APP_ENV=stable'
    $defines += '--dart-define=APP_ASSET_SUFFIX=windows-amd64-compatible-portable.zip'
    if ($Action -eq 'Run') {
        & $FlutterPath run -d windows --no-pub @defines
    } else {
        $mode = if ($Configuration -eq 'Debug') { '--debug' } else { '--release' }
        & $FlutterPath build windows $mode --no-pub @defines
    }
    if ($LASTEXITCODE -ne 0) { throw "Flutter $Action failed ($LASTEXITCODE)." }
} finally {
    Pop-Location
}
